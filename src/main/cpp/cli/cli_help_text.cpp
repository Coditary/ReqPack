HelpScanResult scan_help_arguments(const std::vector<std::string>& arguments) {
    HelpScanResult result;
    for (const std::string& argument : arguments) {
        if (is_help_flag_argument(argument)) {
            result.hasHelp = true;
            continue;
        }
        if (result.dedicatedCommand.empty()) {
            const std::string normalized = to_lower_copy(argument);
            if (normalized == "security" || normalized == "version" || normalized == "self-update" ||
                normalized == "test-plugin" || normalized == "plugin") {
                result.dedicatedCommand = normalized;
                continue;
            }
        }
        if (result.action == ActionType::UNKNOWN) {
            const ActionType candidate = parse_action_token(argument);
            if (candidate != ActionType::UNKNOWN) {
                result.action = candidate;
            }
        }
    }
    return result;
}

